/** Stage 3 output: everything Slang said, with no opinion about it. `[ls_*]` arguments are still the author's text. */
namespace lodestone
{

using RawPlacement = ResourcePlacement;

enum class RawSizeAttributeKind : uint8_t
{
    Invalid = 0,
    ElementCount,
    Extent1d,
    Extent2d,
    Extent3d,
};

std::string_view ToString(RawSizeAttributeKind kind) noexcept;

int32_t ArgumentCountOf(RawSizeAttributeKind kind) noexcept;

/** One `[ls_*]` annotation as written. A string is the only way to stop Slang folding it. */
struct RawSizeAttribute
{
    uint32_t BindingIndex{ 0u };
    RawSizeAttributeKind Kind{ RawSizeAttributeKind::Invalid };
    std::vector<std::string> Arguments;
};

struct RawAxisDeclaration
{
    std::string Name;
    bool IsBooleanAxis{ false }; // axis with ls_boolean_axis attribute
    bool IsInterfaceAxis{ false }; // axis with ls_axis_interface attribute
    bool IsEnumAxis{ false }; // axis with ls_axis_enum attribute
    std::string AxisValues; // unparsed ls_axis_values arg
    std::string ActiveWhen; // unparsed ls_axis_active_when
    std::string Kind; // unparsed ls_axis_kind arg
    std::string SourceFile;
    int32_t SourceLine;
    int32_t SourceColumn;
    std::string RootName;
    // synthetic modules import this to resolve the type
    std::string RootModule;
    std::vector<RawInterfaceImpl> InterfaceImpls; // structs tagged with ls_axis_interface_impl attribute
    std::vector<RawEnumCase> EnumCases; // generated by parsing reflection data for enum named by RootName
    // literal initializers only, so this is empty for an expression or an interface axis
    std::optional<int64_t> ReflectedDefault;
};


/** What a resource is and where it lives. Footprints and visibility are per variant, so they are not here. */
struct RawBinding
{
    std::string Name;
    std::string ScopeName;
    RawPlacement Placement;
    BindingKind Kind{ BindingKind::Invalid };

    uint32_t ElementStride{ 0u };
    uint64_t ByteSize{ 0u };
    // 0 for an unbounded binding array
    uint32_t ArrayCount{ 1u };

    ResourceShape Shape{ ResourceShape::Invalid };
    TextureSampleType SampleType{ TextureSampleType::Invalid };
    TextureFormat StorageFormat{ TextureFormat::Invalid };
    ResourceAccess Access{ ResourceAccess::Invalid };
    bool IsComparisonSampler{ false };

    std::vector<ReflectedUniformMember> UniformMembers;

    /** As written. Stage 4 splits and checks them. */
    std::string RawRoles;
    std::string RawTags;
};

/** Entry point constants in one target's layout. `ContainerBinding` is set for `UniformBuffer` only. */
struct RawEntryPointConstants
{
    EntryPointConstantsDelivery Delivery{ EntryPointConstantsDelivery::None };
    uint32_t ByteSize{ 0u };
    std::optional<uint32_t> ContainerBinding;
    std::vector<ReflectedUniformMember> Members;
};

struct RawEntryPoint
{
    std::string Name;
    std::string VariantSuffix;
    ShaderStageKind Stage{ ShaderStageKind::Invalid };
    WorkgroupSize Workgroup;
    std::vector<std::byte> TargetCode;
    std::optional<std::vector<std::byte>> BaseTargetCode;
    /** Visibility, in placement order. */
    std::vector<uint32_t> UsedBindingIndices;
    ReflectedRasterState Raster;
    RawEntryPointConstants Constants;
};

struct RawVariant
{
    std::string VariantSuffix;
    std::string VariantDescription;
    uint64_t VariantIndex{ 0u };
    std::vector<RawBinding> Bindings;
    std::vector<RawSizeAttribute> SizeAttributes;
    std::vector<RawEntryPoint> EntryPoints;
};

/** A non-`extern` module-scope `static const` as written. Stage 4 evaluates it per variant. */
struct RawDerivedConstant
{
    std::string Name;
    std::string Expression;
    std::string SourceFile;
    uint32_t SourceLine{ 0u };
};

/** @brief An `extern struct` whose interface is in the shim table. The profile decides which implementation links. */
struct RawShimExtern
{
    std::string Name;
    std::string Interface;
    /** @brief The type argument of the interface, as written. Empty for an interface with none. */
    std::string TypeArguments;
    /** @brief Source module that declares the type. */
    std::vector<std::string> ArgumentModules;
    ShimResourceClass Class{ ShimResourceClass::Invalid };
    /** @brief Empty without `ls_storage_format`. */
    std::string FormatAxis;
    std::string SourceFile;
    uint32_t SourceLine{ 0u };
};

/** @brief `extern 'Points' of 'IReadBuffer<PointLight>'`, for diagnostics. */
std::string DescribeShimExtern(const RawShimExtern& shim_extern);

/** Stage 3's module output. `ExternDefaults` carries the undriven extern constants' defaults, which only Slang knows. */
struct RawModule
{
    std::string Name;
    std::vector<std::string> EntryPointNames;
    std::vector<ExternConstantDefault> ExternDefaults;
    std::vector<RawDerivedConstant> DerivedConstants;
    std::vector<RawShimExtern> ShimExterns;
    std::vector<RawVariant> Variants;
};

struct RawLibrary
{
    std::vector<RawModule> Modules;
};

} // namespace lodestone

#endif // !LODESTONE_RAW_LIBRARY_HPP
