#include <string>
#include <string_view>
#include <vector>

/** What stage 3 produces: everything the compiler said, and no opinion about any of it.
 *
 * Stage 3 is the only stage that talks to Slang.The interfaces name and use no Slang types,
 * so that dependencies on the compiler can stay precisely isolated to this stage. It carries
 * through our meta-annotations without interpreting them, ensuring that stage 4 can evaluate
 * those alongside the retrieved compiler information to fully build resource information
 * (thus why it's the "resolve" step)
 *
 * A binding record here holds **placement** and the shape of the resource. It holds no visibility and
 * no footprint, because those have different keys and different lifetimes. Additionally, most of our
 * visiblity and footprint information is dependent on the permutation system and is highly
 * variant-specific.*/
namespace lodestone
{

/** Placement is shared vocabulary rather than a stage 3 concept, so it is defined in the data schema, and
 * stage 4 passes it through unchanged. */
using RawPlacement = ResourcePlacement;

enum class RawSizeAttributeKind : uint8_t
{
    Invalid = 0,
    ElementCount,
    Extent1d,
    Extent2d,
    Extent3d,
};

std::string_view ToString(RawSizeAttributeKind kind) noexcept;

/** How many arguments the attribute of this kind takes. */
uint32_t ArgumentCountOf(RawSizeAttributeKind kind) noexcept;

/** One `[ls_*]` annotation, exactly as the shader author wrote it.
 *
 * Size attributes travel as strings because it's the only way to stop slang
 * from evaluating them for us - so this lets us evaluate them when we want to. */
struct RawSizeAttribute
{
    /** Index into `RawVariant::Bindings`. */
    uint32_t BindingIndex{ 0u };
    RawSizeAttributeKind Kind{ RawSizeAttributeKind::Invalid };
    std::vector<std::string> Arguments;
};

struct RawAxisDeclaration
{
    std::string Name;
    bool IsBooleanAxis{ false }; // axis with ls_boolean_axis attribute
    bool IsInterfaceAxis{ false }; // axis with ls_axis_interface attribute
    bool IsEnumAxis{ false }; // axis with ls_axis_enum attribute
    std::string AxisValues; // unparsed ls_axis_values arg
    std::string ActiveWhen; // unparsed ls_axis_active_when
    std::string Kind; // unparsed ls_axis_kind arg
    std::string SourceFile;
    int32_t SourceLine;
    int32_t SourceColumn;
    // root interface type name, or root enum type name depending on axis type
    std::string RootName;
    // module that declares RootName's type. synthetic modules will need to import
    // this so that they can resolve the type (as appropriate) correctly.
    std::string RootModule;
    std::vector<RawInterfaceImpl> InterfaceImpls; // structs tagged with ls_axis_interface_impl attribute
    std::vector<RawEnumCase> EnumCases; // generated by parsing reflection data for enum named by RootName
    // the initializer as read by Slang reflection: 0 or 1 for a boolean axis, the value for an integral axis,
    // and the case tag for an enum axis. Slang only returns literal initializers, so this is empty for an
    // expression, and always empty for an interface axis. stage 4 compares it against the source text
    std::optional<int64_t> ReflectedDefault;
};


/** What a resource is, and where it lives. Not how much of it, and not who reads it.
 *
 * `ElementStride` and `ByteSize` come from the type layout rather than from an annotation, so they are
 * properties of the declared type and stay here. The footprint an author asked for with a `[ls_*]`
 * annotation is per variant, and it travels in `RawVariant::SizeAttributes`. */
struct RawBinding
{
    std::string Name;
    std::string ScopeName;
    RawPlacement Placement;
    BindingKind Kind{ BindingKind::Invalid };

    uint32_t ElementStride{ 0u };
    uint64_t ByteSize{ 0u };
    uint32_t ArrayCount{ 1u };

    ResourceShape Shape{ ResourceShape::Invalid };
    TextureSampleType SampleType{ TextureSampleType::Invalid };
    TextureFormat StorageFormat{ TextureFormat::Invalid };
    ResourceAccess Access{ ResourceAccess::Invalid };
    bool IsComparisonSampler{ false };

    std::vector<ReflectedUniformMember> UniformMembers;

    /** The argument of `[ls_resource_role]` and of `[ls_resource_tags]`, as the author wrote it. Empty when the
     * resource has no such attribute. Stage 4 splits and checks them. */
    std::string RawRoles;
    std::string RawTags;
};

/** The `uniform` parameters of ordinary data on one entry point, as Slang lays them out for one target. The
 * byte size and the member offsets follow the target's layout rules, so the two targets of one variant can
 * differ. `ContainerBinding` is the index in `RawVariant::Bindings` of the uniform buffer that contains the
 * data, and it is set only when `Delivery` is `UniformBuffer`. */
struct RawEntryPointConstants
{
    EntryPointConstantsDelivery Delivery{ EntryPointConstantsDelivery::None };
    uint32_t ByteSize{ 0u };
    std::optional<uint32_t> ContainerBinding;
    std::vector<ReflectedUniformMember> Members;
};

struct RawEntryPoint
{
    std::string Name;
    std::string VariantSuffix;
    ShaderStageKind Stage{ ShaderStageKind::Invalid };
    WorkgroupSize Workgroup;
    /** The text the target backend generated. Stage 3 does not read it. */
    std::vector<std::byte> TargetCode;
    /** Indices into `RawVariant::Bindings`, in placement order (`PlacementLess`). This is visibility. */
    std::vector<uint32_t> UsedBindingIndices;
    ReflectedRasterState Raster;
    RawEntryPointConstants Constants;
    /** Indices in `RawVariant::Bindings` of the resources in the element of the entry point constants' buffer.
     * Slang's metadata reports each of them as used when any part of the buffer is used (shader-slang/slang#13789),
     * so their visibility is settled against the emitted code later. */
    std::vector<uint32_t> ConstantsElementBindings;
};

struct RawVariant
{
    std::string VariantSuffix;
    std::string VariantDescription;
    uint64_t VariantIndex{ 0u };
    std::vector<RawBinding> Bindings;
    /** Unevaluated. Stage 4 turns these into numbers. */
    std::vector<RawSizeAttribute> SizeAttributes;
    std::vector<RawEntryPoint> EntryPoints;
};

/** A module-scope `static const` that is not `extern`, with its initializer as written. Size expressions can
 * name these. The expression can depend on axis values, so stage 3 does not evaluate it: stage 4 evaluates it
 * for each variant that needs it. The source location is used in error messages, because nothing else
 * checks the value. */
struct RawDerivedConstant
{
    std::string Name;
    std::string Expression;
    std::string SourceFile;
    uint32_t SourceLine{ 0u };
};

/** Stage 3's per-module output.
 *
 * `ExternDefaults` is easy to miss and stage 4 cannot work without it. A size expression may name an
 * `extern static const` constant that no axis drives, and only Slang knows what that constant
 * defaults to. Stage 4 must not call Slang, so the defaults travel here. */
struct RawModule
{
    std::string Name;
    std::vector<std::string> EntryPointNames;
    std::vector<ExternConstantDefault> ExternDefaults;
    std::vector<RawDerivedConstant> DerivedConstants;
    std::vector<RawVariant> Variants;
};

struct RawLibrary
{
    std::vector<RawModule> Modules;
};

} // namespace lodestone

#endif // !LODESTONE_RAW_LIBRARY_HPP
